export const messages: Record<AppLocale, Record<MessageKey, string>> = {
  en: english,
  "zh-CN": simplifiedChinese,
};

export function resolveLocale(savedLocale: string | null, browserLocales: readonly string[]): AppLocale {
  if (savedLocale === "en" || savedLocale === "zh-CN") return savedLocale;
  return browserLocales.some((locale) => locale.toLowerCase().startsWith("zh")) ? "zh-CN" : "en";
}

export function translate(
  locale: AppLocale,
  key: MessageKey,
  values: Record<string, string | number> = {},
): string {
  return messages[locale][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.hasOwn(values, name) ? String(values[name]) : match,
  );
}
